import { useQuery } from "@tanstack/react-query";
import { listAlerts } from "@/api/alerts";
import Card from "@/components/ui/Card";
import Badge from "@/components/ui/Badge";
import ErrorState from "@/components/ui/ErrorState";
import { formatDateTime } from "@/lib/format";

export default function AdminAlerts() {
  const query = useQuery({
    queryKey: ["admin", "alerts"],
    queryFn: () => listAlerts({ page: 1, page_size: 100 }),
  });

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-2xl font-semibold text-text-primary">Alerts</h1>
        <p className="text-sm text-text-muted mt-1">
          All alerts generated by the monitoring engine
        </p>
      </div>

      <Card padded={false}>
        {query.isLoading && (
          <div className="p-6 text-sm text-text-muted">Loading...</div>
        )}
        {query.isError && (
          <ErrorState
            message={
              query.error instanceof Error
                ? query.error.message
                : "Failed to load"
            }
            onRetry={() => query.refetch()}
          />
        )}
        {query.data && (
          <div className="overflow-x-auto">
            <table className="min-w-full text-sm">
              <thead className="bg-surface">
                <tr>
                  <th className="px-4 py-2 text-left font-medium text-text-secondary">
                    Type
                  </th>
                  <th className="px-4 py-2 text-left font-medium text-text-secondary">
                    Site
                  </th>
                  <th className="px-4 py-2 text-left font-medium text-text-secondary">
                    Severity
                  </th>
                  <th className="px-4 py-2 text-left font-medium text-text-secondary">
                    Status
                  </th>
                  <th className="px-4 py-2 text-left font-medium text-text-secondary">
                    Created
                  </th>
                </tr>
              </thead>
              <tbody className="divide-y divide-border-subtle">
                {query.data.items.map((a) => (
                  <tr key={a.id} className="hover:bg-surface">
                    <td className="px-4 py-2">{a.alert_type ?? "\u2014"}</td>
                    <td className="px-4 py-2">{a.site ?? "\u2014"}</td>
                    <td className="px-4 py-2">
                      {a.severity ? (
                        <Badge
                          tone={
                            a.severity === "high"
                              ? "danger"
                              : a.severity === "medium"
                                ? "warning"
                                : "gray"
                          }
                        >
                          {a.severity}
                        </Badge>
                      ) : (
                        "\u2014"
                      )}
                    </td>
                    <td className="px-4 py-2">
                      <Badge tone={a.is_resolved ? "success" : "warning"}>
                        {a.is_resolved ? "Resolved" : "Open"}
                      </Badge>
                    </td>
                    <td className="px-4 py-2 text-text-muted">
                      {formatDateTime(a.created_at)}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </Card>
    </div>
  );
}